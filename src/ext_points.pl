:- multifile metta_memoized_dispatch_call/4.
:- multifile metta_on_function_changed/1.
:- multifile metta_on_function_removed/1.

metta_memoized_dispatch_call(_, _, _, _) :- fail.
metta_on_function_changed(_).
metta_on_function_removed(_).

% Extension points used by the optional debugger (src/debugger/). Each default
% below makes the hook inert, so core behaves exactly as if no extension were
% loaded. Transform hooks fail by default and their call sites fall back to the
% untransformed value; notification hooks succeed and do nothing.

% Wrap one goal of a runnable form before it is called. GoalIndex is the goal's
% position in the form, used by extensions to label the event.
:- multifile metta_wrap_goal/3.
metta_wrap_goal(_, _, _) :- fail.

% Wrap a call goal as it is generated by the translator. SourceExpr is the MeTTa
% expression the goal was compiled from, carrying the live variables, so an
% extension can map the runtime goal back to its source.
:- multifile metta_wrap_compiled_goal/3.
metta_wrap_compiled_goal(_, _, _) :- fail.

% Observe an atomspace operation. Op is add, remove, match or get_atoms; Stage is
% success or fail; Result is the operation's outcome where it has one.
% Deliberately declared with no default clause: call sites wrap it in ignore/1,
% so with no extension loaded the call fails and is discarded, and with one
% loaded it runs exactly once. A no-op default clause here would instead make
% every call site succeed twice over, duplicating solutions.
:- multifile metta_on_space_event/5.

% Take over the command line before the normal dispatch in main/0. Succeeding
% means the extension handled the invocation.
:- multifile metta_main_override/1.
metta_main_override(_) :- fail.

% Run a translation goal with the form's variable-name environment (Name-Var
% pairs, from sread/3) in scope, so an extension can map compiled goals back to
% the MeTTa $variables they came from. No default clause: the call site uses a
% soft cut and falls back to calling the goal directly.
:- multifile metta_with_form_env/2.

% Announce each top-level form as it is parsed, in source order, with its line.
% Lets an extension number the forms without core having to carry an index.
% No default clause: call sites wrap it in ignore/1.
:- multifile metta_on_form_parsed/2.

% The value a top-level !(...) form evaluated to. No default clause; the call
% site wraps it in ignore/1.
:- multifile metta_on_form_result/2.
