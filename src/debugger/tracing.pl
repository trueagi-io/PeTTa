% Runtime goal tracing for the PeTTa debugger.
%
% This is the machinery that used to live in src/metta.pl. It is reached only
% through the extension points declared in src/ext_points.pl, so core carries a
% hook call rather than any debugger logic, and nothing here runs - or is even
% emitted into compiled code - unless the debugger is loaded and a debug flag is
% set.

:- dynamic debug_trace_success/1.

%%% Extension-point implementations %%%

% One goal of a runnable form, wrapped for tracing. Fails when tracing is off so
% the call site in core falls back to the untransformed goal.
metta_wrap_goal(Goal, GoalIndex, Instrumented) :-
    runtime_tracing_active,
    instrument_goal(Goal, meta(eval, 0, eval), GoalIndex, Instrumented).

% A call goal generated by the translator, wrapped so the runtime event can be
% mapped back to the source form and its named variables. Deciding this at
% translation time means a non-debug run compiles to exactly the same clauses it
% did before.
metta_wrap_compiled_goal(SourceExpr, Goal,
                         trace_compiled_goal(Index, Line, SourceExpr, Bindings, Goal)) :-
    debugger_loaded_for_compile,
    current_form_line(Index, Line),
    source_expr_bindings(SourceExpr, Bindings).

% Core publishes the form being translated through declaration_provenance/1
% (with_form_location/3 in src/filereader.pl), so the debugger reads the real
% source line from there rather than keeping its own copy in core.
current_form_line(Index, Line) :-
    catch(declaration_provenance(source(_File, Line)), _, fail),
    integer(Line),
    !,
    ( debug_form_index(Line, Index) -> true ; Index = Line ).
current_form_line(compiled, 0).

%%% Form numbering %%%

% Implements metta_on_form_parsed/2. Core announces every top-level form in
% source order as it is parsed, so the debugger can number them itself and
% report "#<form> line <line>" without core carrying a form index.
:- dynamic debug_form_index/2.
:- dynamic debug_form_counter/1.

metta_on_form_parsed(Line, _FormStr) :-
    ( retract(debug_form_counter(N)) -> true ; N = 0 ),
    N1 is N + 1,
    assertz(debug_form_counter(N1)),
    ( debug_form_index(Line, _) -> true ; assertz(debug_form_index(Line, N1)) ).

% The translator-side wrapper is only worth emitting when a debug flag asked for
% it; otherwise the generated clause stays byte-identical to an undebugged run.
debugger_loaded_for_compile :- debug_category(_), !.
debugger_loaded_for_compile :- debug_break_target(_), !.
debugger_loaded_for_compile :- debug_break_condition(_, _, _), !.
debugger_loaded_for_compile :- debug_break_line(_), !.

%%% Goal instrumentation %%%

instrument_goal(Goal, _, _, Goal) :-
    var(Goal),
    !.
instrument_goal((A,B), Meta, Path, (IA,IB)) :-
    !,
    child_goal_path(Path, 1, PathA),
    child_goal_path(Path, 2, PathB),
    instrument_goal(A, Meta, PathA, IA),
    instrument_goal(B, Meta, PathB, IB).
instrument_goal((A;B), Meta, Path, (IA;IB)) :-
    !,
    child_goal_path(Path, 1, PathA),
    child_goal_path(Path, 2, PathB),
    instrument_goal(A, Meta, PathA, IA),
    instrument_goal(B, Meta, PathB, IB).
instrument_goal((A->B), Meta, Path, (IA->IB)) :-
    !,
    child_goal_path(Path, 1, PathA),
    child_goal_path(Path, 2, PathB),
    instrument_goal(A, Meta, PathA, IA),
    instrument_goal(B, Meta, PathB, IB).
instrument_goal(findall(Template, Goal, Bag), Meta, Path, Instrumented) :-
    !,
    child_goal_path(Path, 1, InnerPath),
    instrument_goal(Goal, Meta, InnerPath, InstrumentedGoal),
    InstrumentedCall = findall(Template, InstrumentedGoal, Bag),
    Instrumented = trace_goal_execution(Meta, Path, InstrumentedCall).
instrument_goal(once(Goal), Meta, Path, Instrumented) :-
    !,
    child_goal_path(Path, 1, InnerPath),
    instrument_goal(Goal, Meta, InnerPath, InstrumentedGoal),
    Instrumented = trace_goal_execution(Meta, Path, once(InstrumentedGoal)).
instrument_goal(Goal, Meta, Path, trace_goal_execution(Meta, Path, Goal)).

child_goal_path(Path, Child, [Path,Child]) :-
    integer(Path),
    !.
child_goal_path(Path, Child, NextPath) :-
    append(Path, [Child], NextPath).

%%% Ports %%%

% When no runtime tracing is requested this must be a transparent no-op:
% rewriting it to anything other than call(Goal) (e.g. the call-stack
% bookkeeping below) corrupts backtracking and collapses nondeterministic
% MeTTa goals to their first solution.
trace_goal_execution(_Meta, _GoalIndex, Goal) :-
    \+ runtime_tracing_active,
    !,
    call(Goal).
trace_goal_execution(Meta, GoalIndex, Goal) :-
    % setup_call_cleanup pushes the frame once and pops it exactly once when
    % Goal is finished (deterministic exit, failure, error, or cut), so the
    % shared metta_call_stack is not re-popped on every backtrack.
    setup_call_cleanup(
        call_stack_push(Goal),
        ( maybe_debug_runtime(enter, Meta, GoalIndex, Goal),
          traced_goal_body(Meta, GoalIndex, Goal)
        ),
        call_stack_pop(Goal)
    ).

traced_goal_body(Meta, GoalIndex, Goal) :-
    fresh_trace_id(TraceId),
    retractall(debug_trace_success(TraceId)),
    call_cleanup(
        traced_goal_port(TraceId, Meta, GoalIndex, Goal),
        cleanup_traced_goal(TraceId, Meta, GoalIndex, Goal)
    ).

trace_compiled_goal(Index, Line, SourceExpr, Bindings, Goal) :-
    runtime_tracing_active,
    !,
    Meta = meta(Index, Line, compiled(SourceExpr, Bindings)),
    GoalIndex = compiled,
    setup_call_cleanup(
        call_stack_push(Goal),
        ( maybe_debug_runtime(enter, Meta, GoalIndex, Goal),
          traced_goal_body(Meta, GoalIndex, Goal)
        ),
        call_stack_pop(Goal)
    ).
trace_compiled_goal(_Index, _Line, _SourceExpr, _Bindings, Goal) :-
    call(Goal).

fresh_trace_id(TraceId) :-
    flag(debug_trace_id, TraceId, TraceId + 1).

traced_goal_port(TraceId, Meta, GoalIndex, Goal) :-
    call(Goal),
    % First solution: record the success. Every later solution is reached by
    % backtracking into the goal, so emit a `redo` port before its success.
    % This makes nondeterministic MeTTa goals (match, superpose, case, ...)
    % render as ENTER -> OK -> REDO -> OK -> ... instead of collapsing to one OK.
    ( debug_trace_success(TraceId)
      -> maybe_debug_runtime(redo, Meta, GoalIndex, Goal)
      ;  assertz(debug_trace_success(TraceId))
    ),
    maybe_debug_runtime(success, Meta, GoalIndex, Goal).

cleanup_traced_goal(TraceId, Meta, GoalIndex, Goal) :-
    ( retract(debug_trace_success(TraceId))
      -> true
      ; maybe_debug_runtime(fail, Meta, GoalIndex, Goal)
    ).

runtime_tracing_active :-
    % While a breakpoint REPL evaluation is in progress, tracing is suspended so
    % the evaluated expression does not recursively trigger instrumentation,
    % breakpoints, or call-stack mutation.
    debug_eval_suspended,
    !,
    fail.
runtime_tracing_active :-
    debug_enabled(runtime).
runtime_tracing_active :-
    debug_break_target(_).
runtime_tracing_active :-
    debug_break_condition(_, _, _).
runtime_tracing_active :-
    debug_break_line(_).
runtime_tracing_active :-
    debug_break_once.

maybe_debug_runtime(_Stage, _Meta, _GoalIndex, _Goal) :-
    \+ runtime_tracing_active,
    !.
maybe_debug_runtime(Stage, Meta, GoalIndex, Goal) :-
    ( runtime_event_enabled(Stage, Goal),
      ( runtime_goal_enabled(Goal)
      ; breakpoint_goal_enabled(Goal)
      ; breakpoint_condition_enabled(Stage, Goal)
      )
      -> debug_event(runtime, Meta, goal(Stage, GoalIndex, Goal))
      ; true
    ).

%%% Source location of the form being translated %%%

% The form's variable-name environment (Name-Var pairs) is passed via the
% backtrackable global current_compile_vars instead of a dynamic predicate:
% assertz/nb_setval copy the term and would sever the variable identity we need,
% whereas b_setval keeps the live variables shared with the clause being built.
:- initialization(nb_setval(current_compile_vars, [])).

% Implements the metta_with_form_env/2 extension point: hold the form's
% variable-name environment while core translates it. b_setval keeps the
% variables identical to the clause being built (assertz would copy them).
metta_with_form_env(Env, Goal) :-
    setup_call_cleanup(
        b_setval(current_compile_vars, Env),
        Goal,
        nb_setval(current_compile_vars, [])
    ).

% Select the Name-Var pairs from the current form's parse environment whose
% variable actually occurs in this call's SourceExpr. The collected pairs must
% reference the live SourceExpr variables (so they bind together with the goal at
% runtime), which rules out findall/copy_term; collect_named_vars/3 walks the
% list preserving identity. Falls back to [] when no environment is available.
source_expr_bindings(SourceExpr, Bindings) :-
    ( catch(b_getval(current_compile_vars, Env), _, fail), is_list(Env)
      -> term_variables(SourceExpr, Vars),
         collect_named_vars(Env, Vars, Bindings)
      ; Bindings = []
    ).

collect_named_vars([], _, []).
collect_named_vars([Name-Var|Rest], Vars, Out) :-
    ( ident_member(Var, Vars)
      -> Out = [Name-Var|Out1]
      ;  Out = Out1
    ),
    collect_named_vars(Rest, Vars, Out1).

ident_member(V, [X|_]) :- V == X, !.
ident_member(V, [_|Xs]) :- ident_member(V, Xs).

%%% Atomspace events %%%

% Implements the metta_on_space_event/5 extension point. space_event_enabled/2
% (debugger.pl) decides whether the category is switched on, so an event that
% nobody asked for costs one failed lookup.
metta_on_space_event(Op, Stage, Space, Pattern, Result) :-
    ( space_event_enabled(Op, Stage)
      -> emit_space_event(Op, Stage, Space, Pattern, Result)
      ; true
    ).

emit_space_event(add, _, Space, Term, _) :-
    debug_event(space, meta(space, 0, space), space(add, Space, Term)).
emit_space_event(remove, _, Space, Term, Removed) :-
    debug_event(space, meta(space, 0, space), space(remove, Space, Term, Removed)).
emit_space_event(match, Stage, Space, Pattern, Result) :-
    debug_event(space, meta(space, 0, space), space(match, Stage, Space, Pattern, Result)).
emit_space_event(get_atoms, _, Space, Pattern, _) :-
    debug_event(space, meta(space, 0, space), space(get_atoms, Space, Pattern)).

%%% Command line %%%

% Implements the metta_main_override/1 extension point. The debugger claims the
% command line only when a debug flag is actually present, so an ordinary run
% falls straight through to core's own dispatch.
metta_main_override(Args) :-
    debug_help_requested(Args),
    !,
    print_debug_help.
metta_main_override(Args) :-
    debug_args_present(Args),
    !,
    ( file_argument(Args, File)
      -> ( exists_file(File)
           -> catch(run_metta_main([File]),
                    debug_break_abort,
                    format(user_error, "~n[debugger] aborted by user~n", []))
           ;  format(atom(Msg), "file not found: ~w", [File]),
              debug_usage_error(Msg) )
      ;  debug_usage_error("no .metta file given")
    ).

debug_usage_error(Reason) :-
    format(user_error, "PeTTa: ~w~n", [Reason]),
    format(user_error, "Usage: sh debug.sh <file.metta> [options]   (run 'sh debug.sh --debug-help')~n", []),
    halt(2).

% Implements metta_on_form_result/2: the value a top-level !(...) form produced.
metta_on_form_result(Line, Result) :-
    ( debug_enabled(result) ; debug_format_json ),
    !,
    ( debug_form_index(Line, Index) -> true ; Index = Line ),
    debug_event(result, meta(Index, Line, runnable), Result).
metta_on_form_result(_, _).
